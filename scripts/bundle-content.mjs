import assert from "node:assert/strict";
import { copyFile, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const project = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const generated = resolve(project, "website/generated");
const sourceSelection = await readFile(resolve(project, "website/content/source.json"), "utf8")
  .then(JSON.parse)
  .catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
const freshRoot =
  sourceSelection?.kind === "fresh-visio-extraction"
    ? resolve(project, sourceSelection.root)
    : null;
const flowDirectory = resolve(freshRoot ?? generated, "flows");
const imageDirectory = freshRoot
  ? resolve(freshRoot, "media")
  : resolve(project, "first_aid_converted/canonical_assets");
const provenance = freshRoot
  ? JSON.parse(await readFile(resolve(freshRoot, "content-provenance.json"), "utf8"))
  : undefined;
const mobileData = resolve(project, "mobile/src/data");
const mobileImages = resolve(project, "mobile/assets/pathways");
const webData = resolve(project, "website/web/src/data");
const webImages = resolve(project, "website/web/src/assets/pathways");
const catalog = JSON.parse(
  await readFile(
    freshRoot ? resolve(freshRoot, "catalog.json") : resolve(generated, "public/data/catalog.json"),
    "utf8",
  ),
);
const flows = {};
const mediaIds = new Set();
for (const file of (await readdir(flowDirectory)).sort()) {
  if (!file.endsWith(".json")) continue;
  const flow = JSON.parse(await readFile(resolve(flowDirectory, file), "utf8"));
  const key = "/flows/" + file;
  assert.ok(!Object.hasOwn(flows, key), "Duplicate procedure: " + key);
  flows[key] = flow;
  for (const page of flow.pages) {
    for (const node of page.nodes) {
      for (const media of node.media ?? []) {
        assert.match(media.asset_id, /^img-[a-f0-9]{16}$/u);
        assert.equal(media.url, "/media/" + media.asset_id + ".png");
        mediaIds.add(media.asset_id);
      }
    }
  }
  for (const media of flow.unassigned_media ?? []) {
    assert.match(media.asset_id, /^img-[a-f0-9]{16}$/u);
    assert.equal(media.url, "/media/" + media.asset_id + ".png");
    mediaIds.add(media.asset_id);
  }
}
assert.equal(Object.keys(catalog.procedures).length, 111);
assert.equal(Object.keys(flows).length, 116);
assert.equal(mediaIds.size, 97);
for (const record of Object.values(catalog.procedures)) {
  assert.ok(Object.hasOwn(flows, record.path), "Missing bundled procedure: " + record.document_id);
}
for (const items of Object.values(catalog.age_groups)) {
  for (const item of items) {
    const record = catalog.procedures[item.procedure_id];
    assert.ok(record, "Missing catalog procedure: " + item.procedure_id);
    const flow = flows[record.path];
    const entry = item.entry_node_id ?? flow.pages[0]?.entry_node_id;
    assert.ok(
      flow.pages.some((page) => page.nodes.some((node) => node.id === entry)),
      "Invalid entry: " + item.id,
    );
  }
}
for (const directory of [mobileData, mobileImages, webData, webImages])
  await mkdir(directory, { recursive: true });
async function writeChanged(file, data) {
  const previous = await readFile(file).catch((error) => {
    if (error.code !== "ENOENT") throw error;
    return null;
  });
  if (!previous?.equals(Buffer.from(data))) await writeFile(file, data);
}
const ids = [...mediaIds].sort();
for (const id of ids) {
  const source = resolve(imageDirectory, id + ".png");
  const destination = resolve(mobileImages, id + ".png");
  const original = await readFile(source);
  const current = await readFile(destination).catch((error) => {
    if (error.code !== "ENOENT") throw error;
    return null;
  });
  if (!current?.equals(original)) await copyFile(source, destination);
  await writeChanged(resolve(webImages, id + ".png"), original);
}
await writeChanged(
  resolve(mobileData, "library.json"),
  JSON.stringify({ catalog, flows, provenance }) + "\n",
);
await writeChanged(
  resolve(webData, "library.json"),
  JSON.stringify({ catalog, flows, provenance }) + "\n",
);
const mobile = [
  "// Generated by website/scripts/bundle-content.mjs. Do not edit by hand.",
  'import type { ImageSourcePropType } from "react-native";',
  "// prettier-ignore",
  "export const mediaSources: Record<string, ImageSourcePropType> = {",
  ...ids.map((id) => '  "/media/' + id + '.png": require("../../assets/pathways/' + id + '.png"),'),
  "};",
  "",
].join("\r\n");
await writeChanged(resolve(mobileData, "media.ts"), mobile);
const web = [
  "// Generated by website/scripts/bundle-content.mjs. Do not edit by hand.",
  ...ids.map((id, index) => "import image" + index + ' from "../assets/pathways/' + id + '.png";'),
  "export const mediaSources: Record<string, string> = {",
  ...ids.map((id, index) => '  "/media/' + id + '.png": image' + index + ","),
  "};",
  "",
].join("\r\n");
await writeChanged(resolve(webData, "media.ts"), web);
console.log(
  "Bundled 111 selectable procedures, 116 flows, and 97 " +
    (freshRoot ? "original Visio illustrations from the fresh extraction" : "illustrations") +
    " for both apps.",
);
